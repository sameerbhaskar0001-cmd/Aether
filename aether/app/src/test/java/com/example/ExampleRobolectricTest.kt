    private suspend fun <T> waitUntilNotNull(timeoutMs: Long = 10000, provider: suspend () -> T?): T {
        val start = System.currentTimeMillis()
        while (System.currentTimeMillis() - start < timeoutMs) {
            val result = provider()
            if (result != null) return result
            kotlinx.coroutines.delay(20)
        }
        throw AssertionError("Timed out waiting for non-null result after ${timeoutMs}ms")
    }

