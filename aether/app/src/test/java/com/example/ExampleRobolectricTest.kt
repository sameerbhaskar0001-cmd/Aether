    @Test
    fun testMemoryRepositoryOperations() = runBlocking {
        val memory = Memory(
            id = "mem-123",
            content = "Learns Kotlin everyday",
            category = "Learning",
            createdTimestamp = System.currentTimeMillis(),
            lastUpdatedTimestamp = System.currentTimeMillis(),
            sourceConversationId = "conv-123",
            isArchived = false
        )

        // 1. Save and Verify Active
        memoryRepository.saveMemory(memory)
        val activeMemories = memoryRepository.getAllActiveMemories()
        assertEquals(1, activeMemories.size)
        assertEquals("Learns Kotlin everyday", activeMemories.first().content)

        // 2. Update memory
        val updatedMemory = memory.copy(
            content = "Learns Kotlin and Compose everyday",
            category = "Skills"
        )
        memoryRepository.saveMemory(updatedMemory)
        val afterUpdate = memoryRepository.getAllActiveMemories()
        assertEquals(1, afterUpdate.size)
        assertEquals("Learns Kotlin and Compose everyday", afterUpdate.first().content)
        assertEquals("Skills", afterUpdate.first().category)

        // 3. Search memories
        val searchResults = memoryRepository.searchMemories("Compose")
        assertEquals(1, searchResults.size)
        assertEquals("mem-123", searchResults.first().id)

        // 4. Archive memory and Verify Excluded from Active
        val archivedMemory = updatedMemory.copy(isArchived = true)
        memoryRepository.saveMemory(archivedMemory)
        val activeAfterArchive = memoryRepository.getAllActiveMemories()
        assertTrue(activeAfterArchive.isEmpty())

        // 5. Verify still returned in All Memories Flow
        val allMemories = memoryRepository.getAllMemoriesFlow().first()
        assertEquals(1, allMemories.size)
        assertTrue(allMemories.first().isArchived)

        // 6. Permanent Delete
        memoryRepository.deleteMemoryById("mem-123")
        val allAfterDelete = memoryRepository.getAllMemoriesFlow().first()
        assertTrue(allAfterDelete.isEmpty())
    }

    @Test
    fun testRoomMigrationPreservesAndUpgradesData() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val dbName = "test_migration_v2_v3"
        context.deleteDatabase(dbName)
        
        // Use custom standard SQLiteOpenHelper to create and populate a real version 2 DB
        val sdbHelper = object : android.database.sqlite.SQLiteOpenHelper(context, dbName, null, 2) {
            override fun onCreate(db: android.database.sqlite.SQLiteDatabase) {
                db.execSQL("""
                    CREATE TABLE IF NOT EXISTS memories (
                        id TEXT NOT NULL PRIMARY KEY,
                        content TEXT NOT NULL,
                        category TEXT NOT NULL,
                        createdTimestamp INTEGER NOT NULL,
                        lastUpdatedTimestamp INTEGER NOT NULL,
                        sourceConversationId TEXT,
                        isArchived INTEGER NOT NULL DEFAULT 0
                    )
                """)
            }
            override fun onUpgrade(db: android.database.sqlite.SQLiteDatabase, oldVersion: Int, newVersion: Int) {}
        }
        
        val sdb = sdbHelper.writableDatabase
        sdb.execSQL("""
            INSERT INTO memories (id, content, category, createdTimestamp, lastUpdatedTimestamp, sourceConversationId, isArchived)
            VALUES ('mem-v2', 'I love Kotlin', 'Learning', 1000, 2000, 'conv-v2', 0)
        """)
        sdbHelper.close()
        
        // Open the database using FrameworkSQLiteOpenHelper to execute direct SupportSQLiteDatabase operations
        val frameworkDbHelper = androidx.sqlite.db.framework.FrameworkSQLiteOpenHelperFactory().create(
            androidx.sqlite.db.SupportSQLiteOpenHelper.Configuration.builder(context)
                .name(dbName)
                .callback(object : androidx.sqlite.db.SupportSQLiteOpenHelper.Callback(2) {
                    override fun onCreate(db: androidx.sqlite.db.SupportSQLiteDatabase) {}
                    override fun onUpgrade(db: androidx.sqlite.db.SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) {}
                })
                .build()
        )
        val supportDb = frameworkDbHelper.writableDatabase
        
        // Execute the migration directly on the SupportSQLiteDatabase
        AppDatabase.MIGRATION_2_3.migrate(supportDb)
        
        // Assert migrations updated the structure and set correct default values on existing rows
        val cursor = supportDb.query("SELECT * FROM memories WHERE id = 'mem-v2'")
        assertTrue(cursor.moveToFirst())
        
        val idIdx = cursor.getColumnIndex("id")
        val contentIdx = cursor.getColumnIndex("content")
        val confidenceScoreIdx = cursor.getColumnIndex("confidenceScore")
        val stateIdx = cursor.getColumnIndex("state")
        val lastAccessedTimestampIdx = cursor.getColumnIndex("lastAccessedTimestamp")
        val accessCountIdx = cursor.getColumnIndex("accessCount")
        
        assertEquals("mem-v2", cursor.getString(idIdx))
        assertEquals("I love Kotlin", cursor.getString(contentIdx))
        assertEquals(3, cursor.getInt(confidenceScoreIdx))
        assertEquals("CONFIRMED", cursor.getString(stateIdx))
        assertEquals(2000L, cursor.getLong(lastAccessedTimestampIdx))
        assertEquals(0, cursor.getInt(accessCountIdx))
        
        cursor.close()
        frameworkDbHelper.close()
        context.deleteDatabase(dbName)
    }

