    private fun awaitActiveProactiveDelivery(viewModel: ChatViewModel, maxWaitMs: Long = 5000): com.example.ai.proactive.ProactiveDelivery? {
        val start = System.currentTimeMillis()
        while (System.currentTimeMillis() - start < maxWaitMs) {
            org.robolectric.shadows.ShadowLooper.idleMainLooper()
            val current = viewModel.activeProactiveDelivery.value
            if (current != null) return current
            try { Thread.sleep(50) } catch (_: Exception) {}
        }
        org.robolectric.shadows.ShadowLooper.idleMainLooper()
        return viewModel.activeProactiveDelivery.value
    }

